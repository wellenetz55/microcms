"""Reject unreviewed static-site changes during production news rebuilds.

The baseline is reviewed data, never regenerated by the publication workflow.
Intentional site edits require a scoped diff review and baseline update together.
"""
import hashlib
import json
import re
from pathlib import Path


def digest(path, relative):
    data = path.read_bytes()
    if relative == 'index.html':
        text = data.decode('utf-8')
        text, count = re.subn(r'<section[^>]+id="updates".*?</section>',
                             '<!-- CMS NEWS REGION -->', text, flags=re.S)
        if count != 1:
            raise ValueError('Static protection: homepage news region is missing or ambiguous')
        data = text.encode('utf-8')
    return hashlib.sha256(data).hexdigest()


def verify(site, baseline):
    records = json.loads(Path(baseline).read_text())
    if records.get('version') != 1 or not records.get('files'):
        raise ValueError('Static protection: invalid approved baseline')
    changed = []
    for relative, expected in records['files'].items():
        path = Path(site) / relative
        if not path.is_file() or digest(path, relative) != expected:
            changed.append(relative)
    if changed:
        raise ValueError('Static protection stopped publication. Review these changes before updating '
                         'cms/static-baseline.json: ' + ', '.join(changed))
